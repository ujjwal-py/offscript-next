import { prisma } from "../src/lib/prisma";
import { faker } from "@faker-js/faker";
import bcrypt from "bcryptjs";
import type { User, Posts } from "../src/generated/prisma/client"


// ---------- Config ----------
const USER_COUNT = 10;
const POST_COUNT = 40;
const LIKE_ATTEMPTS = 150;
const TAGS = ["tech", "anime", "travel", "music", "food", "gaming"];

async function main() {
    // Wipe in dependency order so foreign keys don't complain
    await prisma.likes.deleteMany();
    await prisma.posts.deleteMany();
    await prisma.user.deleteMany();

    const userHash = await bcrypt.hash("password123", 10);
    const adminHash = await bcrypt.hash("admin123", 10);

    // ---------- Admin ----------
    const admin = await prisma.user.create({
        data: {
            username: "admin",
            email: "admin@offscript.dev",
            password: adminHash,
            role: "ADMIN", // match your actual role enum/value
        },
    });

    // ---------- Users ----------
    // ids are generated by @default(uuid()) in the schema
    const users: User[] = await Promise.all(
        Array.from({ length: USER_COUNT }).map((_, i) =>
            prisma.user.create({
                data: {
                    username: `${faker.internet.username().toLowerCase()}${i}`,
                    email: `user${i}.${faker.internet.email().toLowerCase()}`,
                    password: userHash,
                    // role: "USER",
                },
            })
        )
    );

    const authors = [...users, admin];

    // ---------- Posts (no images for now) ----------
    const posts: Posts[] = await Promise.all(
        Array.from({ length: POST_COUNT }).map((_, i) =>
            prisma.posts.create({
                data: {
                    title: faker.lorem.sentence({ min: 3, max: 8 }),
                    description: faker.lorem.paragraphs({ min: 3, max: 6 }, "\n\n"),
                    tags: faker.helpers.arrayElements(TAGS, { min: 1, max: 3 }),
                    // some pending posts so the admin dashboard has something to review
                    status: i % 5 === 0 ? "PENDING" : "PUBLISHED", // use your real enum values
                    authorId: faker.helpers.arrayElement(authors).id,
                },
            })
        )
    );

    // ---------- Likes ----------
    // unique (userId, postId) pairs to avoid violating the composite key
    const seen = new Set<string>();
    const likeData: { userId: string; postId: string }[] = [];
    for (let i = 0; i < LIKE_ATTEMPTS; i++) {
        const userId = faker.helpers.arrayElement(authors).id;
        const postId = faker.helpers.arrayElement(posts).id;
        const key = `${userId}:${postId}`;
        if (!seen.has(key)) {
            seen.add(key);
            likeData.push({ userId, postId });
        }
    }
    await prisma.likes.createMany({ data: likeData, skipDuplicates: true });

    console.log(
        `Seeded 1 admin, ${users.length} users, ${posts.length} posts, ${likeData.length} likes`
    );
    console.log("Admin login: admin@offscript.dev / admin123");
}

main()
    .catch((e) => {
        console.error(e);
        process.exit(1);
    })
    .finally(() => prisma.$disconnect());